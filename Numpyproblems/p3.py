# Create a NumPy array containing 10 numbers. Find and display the maximum, minimum, sum, and average of the elements.
import numpy as np
arr = np.array([12, 45, 2, 89, 23, 56, 34, 9, 67, 15])
print("Array:", arr)
print("Maximum:", arr.max())
print("Minimum:", arr.min())
print("Sum:", arr.sum())
print("Average:", arr.mean())